//! Precomputed unit-scale primitive vertex slices for flat-shaded shapes,
//! sprite billboards, and ground-plane grids.

use crate::vertex::{SpriteVertex, Vertex};

#[inline]
const fn vert(position: [f32; 3], normal: [f32; 3], uv: [f32; 2]) -> Vertex {
    Vertex {
        position,
        color: [1.0, 1.0, 1.0],
        normal,
        uv,
    }
}

#[inline]
const fn grid_vert(position: [f32; 3], uv: [f32; 2]) -> Vertex {
    Vertex {
        position,
        color: [0.0, 0.0, 0.0],
        normal: [0.0, 1.0, 0.0],
        uv,
    }
}

#[inline]
const fn sprite_vert(position: [f32; 3], uv: [f32; 2]) -> SpriteVertex {
    SpriteVertex {
        position,
        uv,
        normal: [0.0, 0.0, 1.0],
    }
}

